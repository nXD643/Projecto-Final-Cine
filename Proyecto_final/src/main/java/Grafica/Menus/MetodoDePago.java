        Funcion funcionElegida = salaElegida.buscarFuncion(fachada.getCines().getFuncionSeleccionada());
        String funcionFecha = salaElegida.buscarFuncion(fachada.getCines().getFuncionSeleccionada()).getFecha().toString();
